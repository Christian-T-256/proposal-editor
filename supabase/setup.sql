-- Run once in the Supabase SQL editor. The service role is the only application
-- credential used by this project, and it is only read in server-side modules.

insert into storage.buckets (id, name, public)
values ('proposal-content', 'proposal-content', false)
on conflict (id) do update set public = false;

create table if not exists public.proposal_events (
  id bigint generated by default as identity primary key,
  proposal_slug text not null check (proposal_slug ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
  session_id text not null check (char_length(session_id) between 1 and 80),
  event_type text not null check (event_type in ('view', 'engagement')),
  active_seconds integer not null default 0 check (active_seconds between 0 and 3600),
  created_at timestamptz not null default now()
);

create index if not exists proposal_events_slug_created_idx
  on public.proposal_events (proposal_slug, created_at desc);

alter table public.proposal_events enable row level security;

-- No public policies are created. The server-side service role bypasses RLS.
